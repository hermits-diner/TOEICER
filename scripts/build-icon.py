"""Writes src-tauri/icons/app-icon.svg, the source for every app and shortcut icon (TOEICER: briefcase).

The tile is a superellipse ("squircle", continuous curvature like current macOS icons) rather than a
rounded rectangle. Regenerate the platform icons afterwards:
    python scripts/build-icon.py
    npm run tauri icon src-tauri/icons/app-icon.svg   (then delete src-tauri/icons/android and ios)
"""

import math
from pathlib import Path

SIZE = 1024
TILE = 864          # macOS uses 824/1024; a little larger reads better on the Windows desktop
EXPONENT = 5.0      # superellipse exponent; ~5 matches Apple's continuous corners


def squircle(cx: float, cy: float, r: float, n: float = EXPONENT, steps: int = 360) -> str:
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + r * math.copysign(abs(c) ** (2 / n), c)
        y = cy + r * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.1f},{y:.1f}")
    return "M" + " L".join(pts) + " Z"


def main() -> None:
    c = SIZE / 2
    tile = squircle(c, c - 6, TILE / 2)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <!-- Generated by scripts/build-icon.py -->
  <defs>
    <linearGradient id="bg" x1="0.15" y1="0" x2="0.85" y2="1">
      <stop offset="0" stop-color="#2ED39A"/>
      <stop offset="0.5" stop-color="#0F8A5F"/>
      <stop offset="1" stop-color="#1F2A2E"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.3" cy="0.12" r="0.75">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.38"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="pageL" x1="0" y1="0" x2="1" y2="0.2">
      <stop offset="0" stop-color="#E9F0FF"/>
      <stop offset="1" stop-color="#FFFFFF"/>
    </linearGradient>
    <linearGradient id="pageR" x1="0" y1="0.2" x2="1" y2="0">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="1" stop-color="#E9F0FF"/>
    </linearGradient>
    <filter id="tileShadow" x="-15%" y="-15%" width="130%" height="135%">
      <feDropShadow dx="0" dy="16" stdDeviation="18" flood-color="#0B1B4D" flood-opacity="0.30"/>
    </filter>
    <filter id="glyphShadow" x="-25%" y="-25%" width="150%" height="160%">
      <feDropShadow dx="0" dy="18" stdDeviation="22" flood-color="#10206B" flood-opacity="0.38"/>
    </filter>
    <clipPath id="clip"><path d="{tile}"/></clipPath>
  </defs>

  <path d="{tile}" fill="url(#bg)" filter="url(#tileShadow)"/>
  <g clip-path="url(#clip)">
    <rect width="{SIZE}" height="{SIZE}" fill="url(#glow)"/>
    <!-- hairline inner edge, as on macOS icons -->
    <path d="{tile}" fill="none" stroke="#FFFFFF" stroke-opacity="0.22" stroke-width="6"/>
  </g>

  <!-- Briefcase: TOEIC's business setting -->
  <g filter="url(#glyphShadow)">
    <path d="M420 330 Q 420 292 458 292 L 566 292 Q 604 292 604 330 L 604 372 L 566 372 L 566 336 Q 566 330 560 330 L 464 330 Q 458 330 458 336 L 458 372 L 420 372 Z" fill="url(#pageL)"/>
    <rect x="232" y="364" width="560" height="372" rx="54" fill="url(#pageR)"/>
  </g>
  <!-- A seam across the case and the orange clasp: the one accent colour -->
  <path d="M232 520 L 792 520" stroke="#A9E3CC" stroke-width="14" stroke-linecap="round" opacity="0.8"/>
  <rect x="470" y="486" width="84" height="74" rx="16" fill="#F28C28"/>
</svg>
"""
    out = Path(__file__).resolve().parent.parent / "src-tauri" / "icons" / "app-icon.svg"
    out.write_text(svg, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
